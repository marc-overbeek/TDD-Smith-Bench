import json
import argparse
from pathlib import Path


def _get_base_hash(repo: str, instance_id: str) -> str:
    """Extract the suffix after the repo name to use as base_hash for regen instance IDs."""
    prefix = f"{repo}."
    if instance_id.startswith(prefix):
        return instance_id[len(prefix):]
    return instance_id


def _normalize_patch_text(text: str) -> str:
    """Normalize patch text for robust equality checks across storage locations."""
    normalized_lines = [line.rstrip() for line in text.replace("\r\n", "\n").replace("\r", "\n").split("\n")]
    return "\n".join(normalized_lines).strip()


def _load_model_patch_map(bug_model_dir: Path) -> dict[str, str]:
    """Load instance_id -> normalized patch text for one model directory."""
    patch_map: dict[str, str] = {}
    if not bug_model_dir.exists():
        return patch_map

    for manifest in bug_model_dir.glob("*_lm_regen_from_tests_attempt_*_patches.json"):
        try:
            entries = json.loads(manifest.read_text())
        except Exception:
            continue
        if not isinstance(entries, list):
            continue

        for entry in entries:
            if not isinstance(entry, dict):
                continue
            instance_id = entry.get("instance_id")
            patch_text = entry.get("patch")
            if not instance_id or not isinstance(patch_text, str):
                continue
            patch_map[instance_id] = _normalize_patch_text(patch_text)

    return patch_map


def _load_all_regen_reports_for_model(
    regen_val_dir: Path,
    repo: str,
    base_hash: str,
    model_patch_map: dict[str, str],
) -> dict[int, list[str]]:
    """Load regen reports filtered to patches generated by one model."""
    reports: dict[int, list[str]] = {}
    prefix = f"{repo}.lm_regen_from_tests__{base_hash}"
    if not regen_val_dir.exists():
        return reports

    for child in regen_val_dir.iterdir():
        if not child.is_dir():
            continue

        attempt = None
        if child.name == prefix:
            attempt = 0
        elif child.name.startswith(prefix) and "__attempt_" in child.name:
            # Accept both legacy IDs:
            #   <repo>.lm_regen_from_tests__<base_hash>__attempt_<n>
            # and model-tagged IDs:
            #   <repo>.lm_regen_from_tests__<base_hash>__model_<model_id>__attempt_<n>
            try:
                attempt_str = child.name.rsplit("__attempt_", 1)[1]
                attempt = int(attempt_str)
            except ValueError:
                attempt = None

        if attempt is None:
            continue

        instance_id = child.name
        model_patch = model_patch_map.get(instance_id)
        if model_patch is None:
            continue

        report_path = child / "report.json"
        patch_path = child / "patch.diff"
        if not report_path.exists() or not patch_path.exists():
            continue

        try:
            validation_patch = _normalize_patch_text(patch_path.read_text())
            if validation_patch != model_patch:
                continue
            report = json.loads(report_path.read_text())
        except Exception:
            continue

        reports[attempt] = report.get("FAIL_TO_PASS", [])

    return reports


def _build_results_for_repo_model(
    repo: str,
    model: str,
    baseline_val_dir: Path,
    regen_val_dir: Path,
    change_dir: Path,
    model_patch_map: dict[str, str],
) -> list[dict]:
    """Build comparison rows for one (repo, model) combo."""
    map_file = change_dir / "_function_map.json"
    if not map_file.exists():
        print(f"[{repo} | {model}] No function map found at {map_file}")
        return []

    fn_map = json.loads(map_file.read_text())
    results = []

    # Load combined test-case map if present so we can include combined-instance validation.
    combined_map = {}
    combined_map_path = change_dir / "_test_case_map.json"
    if combined_map_path.exists():
        try:
            combined_map = json.loads(combined_map_path.read_text())
        except Exception:
            combined_map = {}

    for empty_inst_id, fn_info in fn_map.items():
        empty_report_path = baseline_val_dir / empty_inst_id / "report.json"
        if not empty_report_path.exists():
            continue

        empty_report = json.loads(empty_report_path.read_text())
        empty_broken = empty_report.get("FAIL_TO_PASS", [])
        if len(empty_broken) == 0:
            continue

        base_hash = _get_base_hash(repo, empty_inst_id)
        regen_reports = _load_all_regen_reports_for_model(
            regen_val_dir, repo, base_hash, model_patch_map
        )

        attempt_results = []
        if not regen_reports:
            attempt_results.append({
                "attempt": None,
                "regen_broken": ["<NO_VALIDATION_REPORT_FOUND>"],
            })
        else:
            for attempt in sorted(regen_reports.keys()):
                regen_broken = regen_reports[attempt]
                fixed_tests = set(empty_broken) - set(regen_broken)
                still_broken = set(empty_broken).intersection(set(regen_broken))
                new_broken = set(regen_broken) - set(empty_broken)

                attempt_results.append({
                    "attempt": attempt,
                    "regen_broken": regen_broken,
                    "fixed_count": len(fixed_tests),
                    "still_broken_count": len(still_broken),
                    "new_broken_count": len(new_broken),
                })

        results.append({
            "function": f"{fn_info['file_path']}::{fn_info['function_name']}",
            "empty_fails_count": len(empty_broken),
            "empty_broken": empty_broken,
            "attempts": attempt_results,
        })

    # Process combined instances (groups of functions that were regenerated together).
    for combined_id, combined_info in sorted(combined_map.items()):
        report_path = baseline_val_dir / combined_id / "report.json"
        if not report_path.exists():
            continue

        combined_report = json.loads(report_path.read_text())
        combined_broken = combined_report.get("FAIL_TO_PASS", [])
        if len(combined_broken) == 0:
            continue

        instance_ids = combined_info.get("instance_ids", [])
        functions = []
        for iid in instance_ids:
            fi = fn_map.get(iid)
            if fi:
                functions.append(f"{fi['file_path']}::{fi['function_name']}")

        base_hash = _get_base_hash(repo, combined_id)
        regen_reports = _load_all_regen_reports_for_model(
            regen_val_dir, repo, base_hash, model_patch_map
        )

        attempt_results = []
        if not regen_reports:
            attempt_results.append({
                "attempt": None,
                "regen_broken": ["<NO_VALIDATION_REPORT_FOUND>"],
            })
        else:
            for attempt in sorted(regen_reports.keys()):
                regen_broken = regen_reports[attempt]
                fixed_tests = set(combined_broken) - set(regen_broken)
                still_broken = set(combined_broken).intersection(set(regen_broken))
                new_broken = set(regen_broken) - set(combined_broken)

                attempt_results.append({
                    "attempt": attempt,
                    "regen_broken": regen_broken,
                    "fixed_count": len(fixed_tests),
                    "still_broken_count": len(still_broken),
                    "new_broken_count": len(new_broken),
                })

        results.append({
            "function": f"combined::{combined_id}",
            "instance_ids": instance_ids,
            "functions": functions,
            "empty_fails_count": len(combined_broken),
            "empty_broken": combined_broken,
            "attempts": attempt_results,
        })

    return results


def _discover_repos(change_root: Path, val_root: Path, bug_root: Path) -> list[str]:
    """Discover repos that have change logs, validation, and bug_gen data."""
    if not change_root.exists() or not val_root.exists() or not bug_root.exists():
        return []

    change_repos = {p.name for p in change_root.iterdir() if p.is_dir()}
    val_repos = {p.name for p in val_root.iterdir() if p.is_dir()}
    bug_repos = {p.name for p in bug_root.iterdir() if p.is_dir()}
    return sorted(change_repos.intersection(val_repos).intersection(bug_repos))


def _discover_models(bug_repo_dir: Path) -> list[str]:
    """Discover model directory names for one repo."""
    if not bug_repo_dir.exists():
        return []
    return sorted([p.name for p in bug_repo_dir.iterdir() if p.is_dir()])


def _print_combo_summary(repo: str, model: str, results: list[dict]) -> None:
    """Print compact per-combo metrics."""
    total_fixed = 0
    total_originally_broken = 0

    for row in results:
        total_originally_broken += row["empty_fails_count"]
        valid_attempts = [a for a in row["attempts"] if a["regen_broken"] != ["<NO_VALIDATION_REPORT_FOUND>"]]
        if valid_attempts:
            best_attempt = min(valid_attempts, key=lambda a: len(a["regen_broken"]))
            total_fixed += best_attempt["fixed_count"]

    print(f"[{repo} | {model}] ========================================")
    print(f"[{repo} | {model}] Total originally broken tests  : {total_originally_broken}")
    print(f"[{repo} | {model}] Total tests fixed by LLM regen : {total_fixed}")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("repo", nargs="?", help="Optional repo filter. If omitted, process all repos in logs.")
    parser.add_argument("--model", type=str, default=None, help="Optional model directory filter.")
    parser.add_argument("--logs_root", type=Path, default=Path("logs"), help="Root logs directory (default: logs).")
    args = parser.parse_args()

    logs_root = args.logs_root
    change_root = logs_root / "change_logs"
    val_root = logs_root / "run_validation"
    bug_root = logs_root / "bug_gen"
    results_root = Path("results")
    results_root.mkdir(parents=True, exist_ok=True)

    if args.repo:
        repos = [args.repo]
    else:
        repos = _discover_repos(change_root, val_root, bug_root)

    if not repos:
        print("No repos found to process.")
        return

    generated_files = []

    for repo in repos:
        baseline_val_dir = val_root / repo
        change_dir = change_root / repo
        bug_repo_dir = bug_root / repo

        if not baseline_val_dir.exists() or not change_dir.exists() or not bug_repo_dir.exists():
            print(f"[{repo}] Missing one or more required directories. Skipping.")
            continue

        models = _discover_models(bug_repo_dir)
        if args.model:
            if args.model in models:
                models = [args.model]
            else:
                print(f"[{repo}] Model '{args.model}' not found under {bug_repo_dir}. Skipping repo.")
                continue

        for model in models:
            model_patch_map = _load_model_patch_map(bug_repo_dir / model)
            if not model_patch_map:
                print(f"[{repo} | {model}] No model patch manifests found. Skipping.")
                continue

            model_val_dir = baseline_val_dir / model
            regen_val_dir = model_val_dir if model_val_dir.exists() else baseline_val_dir

            results = _build_results_for_repo_model(
                repo=repo,
                model=model,
                baseline_val_dir=baseline_val_dir,
                regen_val_dir=regen_val_dir,
                change_dir=change_dir,
                model_patch_map=model_patch_map,
            )

            out_file = results_root / f"{repo}__{model}_test_comparison.json"
            out_file.write_text(json.dumps(results, indent=2))
            generated_files.append(str(out_file))

            _print_combo_summary(repo, model, results)
            print(f"[{repo} | {model}] Detailed JSON saved to {out_file}")

    if generated_files:
        print("\nGenerated files:")
        for fpath in generated_files:
            print(f"- {fpath}")
    else:
        print("No comparison files were generated.")

if __name__ == "__main__":
    main()
